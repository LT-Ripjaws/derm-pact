"""Score the v5.3 agent eval report with the RAGAS judge (faithfulness + answer_relevancy).

v5.3 is a measurement-fix release on top of v5.2's prompt: the clinician agent loop itself
gained a conditional second revision (medguard_v2/agent/clinician_agent.py), which bumped
PROMPT_VERSION to "clinician-agent-v5.3" and forces fresh (uncached) agent generation. This
driver's own target, ``run_ragas()`` in ``rerun_agent_and_ragas.py``, gained two independent
measurement fixes that apply regardless of which prompt version produced the answers:

  - Contract-context: 'mixed' (and already-scored 'contract') rows now also get the case's own
    compact decision-contract facts as an extra judge context, so a faithful contract-derived
    statement (score, criteria, classifier output) is no longer judged unfaithful against
    guideline-only contexts it was never supposed to be grounded in (v2's 0.0972 mixed
    faithfulness had exactly this cause; v5.2 mixed was still 0.7762 without the fix).
  - Median-of-3 judging: the judge is nondeterministic at temperature 0 (measured noise floor
    0.0489). Every sample is now judged 3 times, cached independently per attempt, and the
    reported numbers are the per-sample MEDIAN, with a judge_dispersion summary.

This is a minimal driver around ``run_ragas()`` in ``rerun_agent_and_ragas.py``. It does NOT
call ``run_agent_eval()`` and does NOT regenerate the agent report -- ``rerun_agent_and_ragas.py``'s
own ``__main__`` always runs the agent first, and that CLI has no flag to skip it (only
--model/--limit/--cohort), so this driver imports the judging function directly and calls only
that (same pattern as ``run_ragas_v5_2.py``/``run_ragas_v4.py``).

Input:  research/evidence/derm7pt_v1/agent_eval_report_v5_3.json (already generated by
        scripts/dev/run_agent_eval.py --model qwen/qwen3-vl-32b-instruct --limit 203 --cohort all;
        NOT regenerated here)
Output: research/evidence/derm7pt_v1/agent_ragas_metrics_v5_3.json (new file; does NOT touch
        agent_ragas_metrics_v5_2.json or any earlier version)

Judge model: medguard.config.JUDGE_MODEL (the same default every prior run used --
run_ragas() ignores its own `model` parameter and always judges with config.JUDGE_MODEL
internally, so this driver reports that value rather than inventing one).

Cost: ~3x a single-shot judging pass (median-of-3), offset by cache reuse -- any sample whose
guideline-context content happens to exactly match a prior run's (attempt 0, seed=0) replays
free; the contract-context addition and any new v5.3 answer text still requires fresh judging.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

# Load rerun_agent_and_ragas.py by file path (not `import scripts.dev....`) so this
# works regardless of whether scripts/ and scripts/dev/ are set up as packages.
_spec = importlib.util.spec_from_file_location(
    "rerun_agent_and_ragas", REPO / "scripts" / "dev" / "rerun_agent_and_ragas.py"
)
_module = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
_spec.loader.exec_module(_module)
run_ragas = _module.run_ragas

from medguard import config  # noqa: E402


def main() -> None:
    agent_results_path = REPO / "research/evidence/derm7pt_v1/agent_eval_report_v5_3.json"
    out = REPO / "research/evidence/derm7pt_v1/agent_ragas_metrics_v5_3.json"
    v52_path = REPO / "research/evidence/derm7pt_v1/agent_ragas_metrics_v5_2.json"

    if not agent_results_path.exists():
        raise SystemExit(f"missing agent report: {agent_results_path}")

    print(f"agent report : {agent_results_path}")
    print(f"output       : {out}")
    print(f"judge model  : {config.JUDGE_MODEL}  (config.JUDGE_MODEL; run_ragas's own "
          f"`model` arg is accepted but unused -- it always judges with config.JUDGE_MODEL)")
    print(f"judge attempts per sample: {_module.N_JUDGE_ATTEMPTS} (median reported)")

    result = run_ragas(agent_results_path, out, config.JUDGE_MODEL)

    reported_version = json.loads(agent_results_path.read_text(encoding="utf-8")).get("prompt_version")
    print(f"\n  prompt_version (from agent report): {reported_version}")

    if v52_path.exists():
        v52 = json.loads(v52_path.read_text(encoding="utf-8"))
        print("\n=== v5.2 -> v5.3 sample comparison ===")
        print(f"  n_guideline_scorable : {v52.get('n_guideline_scorable')} -> {result.get('n_guideline_scorable')}")
        print(f"  faithfulness         : {v52.get('faithfulness')} -> {result.get('faithfulness')}")
        print(f"  answer_relevancy     : {v52.get('answer_relevancy')} -> {result.get('answer_relevancy')}")
        v52_by_g = v52.get("faithfulness_by_grounding", {})
        v53_by_g = result.get("faithfulness_by_grounding", {})
        # "contract" was not broken out in the v5.2 file (that loop only covered guideline/
        # mixed); v5.3's run_ragas now reports it too, so show "N/A" on the v5.2 side rather
        # than a KeyError-shaped gap.
        for g in ("guideline", "mixed", "contract"):
            print(f"  by_grounding[{g}]     : {v52_by_g.get(g, {}).get('mean', 'N/A')} -> {v53_by_g.get(g, {}).get('mean', 'N/A')}")
        print(f"  judge_dispersion (v5.3 faithfulness): {result.get('judge_dispersion', {}).get('faithfulness')}")


if __name__ == "__main__":
    main()
